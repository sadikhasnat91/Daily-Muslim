BdDistrict? findBdDistrict(String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return null;
  for (final d in kAllBangladeshDistricts) {
    if (d.nameEn.toLowerCase() == q ||
        d.nameBn == query.trim() ||
        d.nameEn.toLowerCase().replaceAll("'", "") == q.replaceAll("'", "") ||
        q.contains(d.nameEn.toLowerCase()) ||
        q.contains(d.nameBn)) {
      return d;
    }
  }
  return null;
}

